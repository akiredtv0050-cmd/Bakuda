def find(name, table):
    for w, s in table:
        if w in name: return s
    return None

def tint_for(name, theme):
    for words, m, k in TINT:
        if any(w in name for w in words): return m, k
    t = THEME_TINT.get(theme)
    return t if t else (None, 0)

def recolor(im, mat, k):
    """明るさを たもったまま 色を ぬりかえる"""
    if not mat or k <= 0: return im
    a = np.asarray(im).astype(np.float32)
    rgb, al = a[..., :3], a[..., 3:]
    L = (rgb @ np.array([0.299, 0.587, 0.114], np.float32)) / 255.0
    ramp = np.array(MAT[mat], np.float32)            # 5 色
    L2 = np.clip(L * 1.08, 0, 1) * 4
    i0 = np.clip(np.floor(L2).astype(int), 0, 3); f = (L2 - i0)[..., None]
    col = ramp[i0] * (1 - f) + ramp[i0 + 1] * f
    out = rgb * (1 - k) + col * k
    return Image.fromarray(np.concatenate([np.clip(out, 0, 255), al], -1).astype(np.uint8), 'RGBA')

def hue_jitter(im, seed, amt=14):
    """同じ形が つづかないように ほんの少し 色を ずらす"""
    r = random.Random(seed); d = r.uniform(-amt, amt) / 360.0
    if abs(d) < 0.005: return im
    a = np.asarray(im.convert('RGBA')).astype(np.float32) / 255.0
    rgb = a[..., :3]; mx = rgb.max(-1); mn = rgb.min(-1); c = mx - mn
    h = np.zeros_like(mx)
    m = c > 1e-6
    rr, gg, bb = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    i = m & (mx == rr); h[i] = ((gg - bb)[i] / c[i]) % 6
    i = m & (mx == gg); h[i] = ((bb - rr)[i] / c[i]) + 2
    i = m & (mx == bb); h[i] = ((rr - gg)[i] / c[i]) + 4
    h = (h / 6 + d) % 1.0
    s = np.where(mx > 0, c / np.maximum(mx, 1e-6), 0); v = mx
    i6 = np.floor(h * 6).astype(int) % 6; f = h * 6 - np.floor(h * 6)
    p, q, t = v * (1 - s), v * (1 - f * s), v * (1 - (1 - f) * s)
    out = np.stack([np.choose(i6, [v, q, p, p, t, v]), np.choose(i6, [t, v, v, q, p, p]), np.choose(i6, [p, p, t, v, v, q])], -1)
    return Image.fromarray((np.concatenate([out, a[..., 3:]], -1) * 255).astype(np.uint8), 'RGBA')

