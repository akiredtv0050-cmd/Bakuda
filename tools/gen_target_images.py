def pixelize(im, margin, glow=None, sparkle=None, top_pad=0):
    w, h = im.size; inner = G - margin * 2
    k = min(inner / w, (inner - top_pad) / h)
    sm = im.resize((max(1, round(w * k)), max(1, round(h * k))), Image.BOX)
    base = Image.new('RGBA', (G, G), (0, 0, 0, 0))
    base.alpha_composite(sm, ((G - sm.size[0]) // 2, G - margin - sm.size[1]))
    a = np.asarray(base).astype(np.int32).copy()
    al = a[..., 3]; keep = al >= 110
    rgb = np.where(al[..., None] > 0, np.minimum(255, a[..., :3] * 255 // np.maximum(al[..., None], 1)), 0)
    rgb = (rgb // 8) * 8
    a = np.concatenate([rgb, np.where(keep, 255, 0)[..., None]], -1).astype(np.uint8)
    small = Image.fromarray(a, 'RGBA'); s = np.asarray(small)[..., 3] > 0
    out = np.zeros((G, G, 4), np.uint8)
    if glow is not None:
        near = np.zeros_like(s)
        for dy in range(-2, 3):
            for dx in range(-2, 3):
                if abs(dx) + abs(dy) <= 3: near |= np.roll(np.roll(s, dy, 0), dx, 1)
        m = near & ~s; out[m] = list(glow) + [110]
    edge = np.zeros_like(s)
    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)): edge |= np.roll(np.roll(s, dy, 0), dx, 1)
    out[edge & ~s] = (26, 16, 32, 255)
    res = Image.fromarray(out, 'RGBA'); res.alpha_composite(small)
    if sparkle is not None:
        r = random.Random(sparkle); px = res.load(); sp = np.asarray(small)
        for _ in range(2):
            for _t in range(50):
                x, y = r.randrange(3, G - 3), r.randrange(3, G - 3)
                if sp[y, x, 3] and int(sp[y, x, :3].sum()) > 330:
                    for dx, dy in ((0, 0), (1, 0), (-1, 0), (0, 1), (0, -1)): px[x + dx, y + dy] = (255, 255, 255, 255)
                    break
    return res

