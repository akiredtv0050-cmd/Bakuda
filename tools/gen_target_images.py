def crown_layer(G):
    """かんむり（ドットで 直接 描く）"""
    c = Image.new('RGBA', (G, G), (0, 0, 0, 0)); p = c.load()
    W = 16; x0 = (G - W) // 2; y0 = 1
    gold, light, dark, red = (246, 200, 64, 255), (255, 242, 160, 255), (160, 106, 8, 255), (255, 58, 74, 255)
    rows = ['..X....X....X...', '.XLX..XLX..XLX..', '.XLX.XLLLX.XLX..', 'XLLLXLLLLLXLLLX.', 'XGGGGGRGGGGGGGX.', 'XGDGGRRRGGDGGGX.', 'XDDDDDDDDDDDDDX.']
    for j, row in enumerate(rows):
        for i, ch in enumerate(row):
            if ch == '.': continue
            p[x0 + i, y0 + j] = {'X': (26, 16, 32, 255), 'L': light, 'G': gold, 'D': dark, 'R': red}[ch]
    return c, y0 + len(rows)

