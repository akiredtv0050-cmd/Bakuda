def draw_golem(P, rnd):
    S = 420; im = Image.new('RGBA', (S, S), (0, 0, 0, 0)); d = ImageDraw.Draw(im); cx = S / 2
    def block(x0, y0, x1, y1, r=18):
        d.rounded_rectangle([x0, y0, x1, y1], r, fill=P[1] + (255,))
        d.rounded_rectangle([x0, y0, x1 - (x1 - x0) * 0.18, y1 - (y1 - y0) * 0.15], r, fill=P[2] + (255,))
        d.rounded_rectangle([x0 + 8, y0 + 8, x0 + (x1 - x0) * 0.4, y0 + (y1 - y0) * 0.3], r // 2, fill=P[3] + (255,))
    bw = rnd.uniform(0.42, 0.5) * S
    block(cx - bw * 0.42, S * 0.72, cx - bw * 0.08, S * 0.98)          # 足
    block(cx + bw * 0.08, S * 0.72, cx + bw * 0.42, S * 0.98)
    block(cx - bw / 2, S * 0.34, cx + bw / 2, S * 0.78, 26)            # からだ
    block(cx - bw / 2 - S * 0.2, S * 0.36, cx - bw / 2 + 4, S * 0.82)   # うで
    block(cx + bw / 2 - 4, S * 0.36, cx + bw / 2 + S * 0.2, S * 0.82)
    block(cx - S * 0.15, S * 0.08, cx + S * 0.15, S * 0.36, 22)        # あたま
    for sx in (-1, 1):                                                    # 光る目
        d.rectangle([cx + sx * 34 - 13, S * 0.19, cx + sx * 34 + 13, S * 0.25], fill=(255, 230, 90, 255))
    # ひび・こうせき
    for _ in range(rnd.randint(2, 4)):
        x = cx + rnd.uniform(-bw * 0.35, bw * 0.3); y = S * rnd.uniform(0.42, 0.7)
        d.line([(x, y), (x + rnd.uniform(-20, 20), y + 24), (x + rnd.uniform(-10, 25), y + 44)], fill=P[0] + (255,), width=6)
    if rnd.random() < 0.6:
        g = (rnd.choice([(255, 80, 90), (90, 220, 255), (120, 255, 140), (255, 210, 60), (200, 120, 255)]))
